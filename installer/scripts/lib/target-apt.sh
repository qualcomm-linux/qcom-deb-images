# scripts/lib/target-apt.sh <build_dir> <suite> <qli_repo>
#
# Sets up APT on the installed system the same way as the debos rootfs
# (debos-recipes/qualcomm-linux-debian-rootfs.yaml):
#  - <suite>-backports, for suites that have it (trixie), through
#    apt-setup's backports service, pinned so that the hardware enablement
#    packages (kernel, firmware, mesa etc.) come from it
#  - with <qli_repo>=1, the Qualcomm Linux repository, through apt-setup's
#    local0 repository, pinned over backports for the packages it overrides.
#    For ISOs with a qcom kernel, so that it gets updates
# Appends the preseed lines to <build_dir>/config/installer-preseed.cfg and
# writes the key and the pins to <build_dir>/config/includes.binary/qli/apt/,
# i.e. /qli/apt/ on the ISO. qcom-laptop-postinst.sh installs the pins on
# the target, as d-i has no preseed for them. Keep the package lists and
# priorities in sync with the debos rootfs recipe.
set -eu

BUILD_DIR=$1
SUITE=$2
QLI_REPO=$3

PRESEED="$BUILD_DIR/config/installer-preseed.cfg"
APT_DIR="$BUILD_DIR/config/includes.binary/qli/apt"
rm -rf "$APT_DIR"
mkdir -p "$APT_DIR"

# The SoC and wifi firmware packages are in non-free-firmware.
cat >> "$PRESEED" <<EOF
# Generated by target-apt.sh: enable non-free-firmware on the target.
d-i apt-setup/non-free-firmware boolean true
EOF

# Only stable suites have backports.
case "$SUITE" in
    trixie)
        cat >> "$PRESEED" <<EOF
# Generated by target-apt.sh: add $SUITE-backports on the target.
d-i apt-setup/services-select multiselect security, updates, backports
EOF

        cat > "$APT_DIR/debian-backports.pref" <<EOF
# for binary packages built from these source packages, score the version from
# Debian backports higher as to get hardware enabled or better hardware support

Package: src:alsa-lib:any src:alsa-ucm-conf:any src:debugcc:any src:efivar:any src:fastrpc:any src:firmware-free:any src:firmware-nonfree:any src:greetd:any src:hexagon-dsp-binaries:any src:linux:any src:linux-base:any src:linux-signed-arm64:any src:mesa:any src:rmtfs:any src:thermald:any src:u-boot-efi-dtb:any src:wireplumber:any src:pipewire:any
Pin: release n=$SUITE-backports
Pin-Priority: 900
EOF
        ;;
esac

if [ "$QLI_REPO" = 1 ]; then
    # apt-setup fetches the key with fetch-url, which takes file:// URLs, and
    # installs it as /etc/apt/keyrings/<comment>.asc.
    cat >> "$PRESEED" <<EOF
# Generated by target-apt.sh: add the Qualcomm Linux repository on the
# target.
d-i apt-setup/local0/repository string https://deb.debusine.qualcomm.com/qualcomm/qli $SUITE main contrib non-free-firmware non-free
d-i apt-setup/local0/comment string Qualcomm Linux
d-i apt-setup/local0/source boolean false
d-i apt-setup/local0/key string file:///cdrom/qli/apt/qli.asc
EOF

    cat > "$APT_DIR/qli.asc" <<EOF
-----BEGIN PGP PUBLIC KEY BLOCK-----

